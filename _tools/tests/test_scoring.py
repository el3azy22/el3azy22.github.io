"""اختبارات الحسابات (بدون إنترنت): «دوري التوقعات» و«دوري الجماهير».
كل حالة: المدخلات ← القاعدة ← المتوقع (محسوب باليد) ← الفعلي.   python3 _tools/tests/test_scoring.py"""
import importlib.util, os, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
def load(name, path):
    sp = importlib.util.spec_from_file_location(name, os.path.join(ROOT, path)); m = importlib.util.module_from_spec(sp); sp.loader.exec_module(m); return m
P = load('pred', '_tools/predict/build.py')
F = load('fans', '_tools/fans/build.py')
ok = fail = 0
def check(name, got, want):
    global ok, fail
    good = got == want; ok += good; fail += not good
    print(('✅' if good else '❌'), name, '→', got, '' if good else f'(المتوقع {want})')

print('— نقاط مباراة التوقعات —')
for (ph, pa, sh, sa), want, why in [
    ((2, 1, 2, 1), 5, 'النتيجة بالضبط'), ((2, 1, 3, 2), 3, 'الفائز والفارق'), ((1, 1, 0, 0), 3, 'تعادل بنتيجة ثانية'),
    ((2, 1, 3, 0), 2, 'الفائز بس'), ((2, 1, 1, 1), 0, 'توقع فوز وصار تعادل'), ((0, 0, 0, 1), 0, 'توقع تعادل وفاز الضيف'),
    ((0, 0, 0, 0), 5, 'صفر-صفر بالضبط'), ((20, 0, 1, 0), 2, 'الفائز بس بفارق مختلف (حد أعلى 20)'), ((1, 2, 0, 1), 3, 'فوز الضيف بنفس الفارق')]:
    check(f'{why}: توقع {ph}-{pa} والنتيجة {sh}-{sa}', P.points(ph, pa, sh, sa), want)

print('\n— جولة توقعات كاملة —')
T0 = 1_800_000_000_000
ms = [{'id': 'A', 'wk': 5, 't': T0, 'h': 'ain', 'a': 'wahda', 'st': 6, 'sh': 2, 'sa': 1},
      {'id': 'B', 'wk': 5, 't': T0 + 3600e3, 'h': 'wasl', 'a': 'nasr', 'st': 6, 'sh': 0, 'sa': 0},
      {'id': 'C', 'wk': 5, 't': T0 + 7200e3, 'h': 'jazira', 'a': 'kalba', 'st': 4},          # تأجلت/ما خلصت
      {'id': 'D', 'wk': 6, 't': T0 + 7 * 86400e3, 'h': 'ajman', 'a': 'hatta', 'st': 6, 'sh': 1, 'sa': 3}]
pk = lambda h, a, w, x=False, c='ain', n='': {'h': h, 'a': a, 'w': w, 'c': c, 'n': n, **({'x': True} if x else {})}
picks = {'A': {'u1': pk(2, 1, T0 - 5, x=True), 'u2': pk(1, 0, T0 - 9), 'u3': pk(2, 1, T0)},          # u3 كتب مع الصافرة = مرفوض
         'B': {'u1': pk(1, 1, T0 - 5, x=True), 'u2': pk(0, 0, T0 - 9, x=True), 'u3': pk(0, 0, T0 - 1)},
         'C': {'u1': pk(1, 0, T0 - 5)},
         'D': {'u1': pk(0, 2, T0 - 5)}}
cr, tb = P.compute(ms, picks, T0 + 9 * 86400e3)
r5 = {row[0]: row for row in tb['rounds']['5']}
# u1: A بالضبط 5 ×2 (أول مضاعفة بالموعد) = 10 · B تعادل بنتيجة ثانية 3 (المضاعفة الثانية ما تنحسب) · C ما خلصت = 0 ⇒ 13، بالضبط 1، مباريات محسوبة 2
check('u1: 13 نقطة، 1 بالضبط، 2 مباريات', r5['u1'][3:], [13, 1, 2])
# u2: A الفائز والفارق 3 · B بالضبط 5 ×2 = 10 ⇒ 13، بالضبط 1
check('u2: 13 نقطة، 1 بالضبط', r5['u2'][3:], [13, 1, 2])
# u3: A مرفوض (مع الصافرة) · B بالضبط 5 ⇒ 5
check('u3: توقع مع الصافرة ما ينحسب ⇒ 5', r5['u3'][3:], [5, 1, 1])
# تعادل u1 و u2 (13، 1 بالضبط): الأقدم في آخر توقع يتقدم. آخر كتابة u1 = T0-5 (C)، u2 = T0-9 ⇒ u2 أول
check('كسر التعادل: الأقدم في التوقع أول', [row[0] for row in tb['rounds']['5']][:2], ['u2', 'u1'])
check('الموسم: ما أحد شارك في 3 جولات ⇒ فاضي', tb['season'], [])
check('رأي الجماهير في A يحسب التوقعات المقبولة بس (2)', cr['A']['n'], 2)

print('\n— نقاط الأندية في التحدي (دوري الجماهير) —')
rp = F.rank_points([('ain', 5.6, 40), ('wahda', 6.1, 70), ('wasl', 5.6, 40), ('nasr', 9.0, 2), ('jazira', 5.6, 41)], 3)
check('الأول بالمعدل ياخذ 14', rp['wahda'][0], 14)
check('تساوي المعدل: الأكثر لعبات (الجزيرة 41) ياخذ 13', rp['jazira'][0], 13)
check('تساوي المعدل واللعبات (العين والوصل): نفس النقاط 12', (rp['ain'][0], rp['wasl'][0]), (12, 12))
check('معدل عالي بس تحت الحد الأدنى (لعبتين) ⇒ 0', rp['nasr'][0], 0)
check('نادي ما لعب ⇒ 0', rp['hatta'], [0, 0, 0])

print('\n— نجوم الأسبوع —')
M = lambda nm, pts, pro, one, at, c='ain': {'nm': nm, 'pts': pts, 'pro': pro, 'one': one, 'at': at, 'c': c}
ind = {'a': M('أ', 30, 12, 3, 500), 'b': M('ب', 30, 14, 1, 900), 'c': M('ج', 30, 14, 2, 900), 'd': M('د', 30, 14, 2, 800),
       'e': M('هـ', 30, 14, 2, 800), 'f': M('و', 0, 0, 0, 1), 'g': M('', 50, 20, 5, 1), 'h': M('ح', 25, 10, 1, 1, c='none'), 'i': M('ط', 10, 0, 0, 1)}
st, more = F.rank_fans(ind, hide={'i'})
got = [(x[0], x[3]) for x in st]
# الكل 30: الخبير 14 يتقدم على 12 · بين 14: من أول محاولة 2 قبل 1 · بين (ج، د، هـ): الأسبق at 800 (د، هـ) ثم ج 900 · د وهـ متساوين بالكامل ⇒ يتشاركون المركز 1
check('ترتيب وفك التعادل والمشاركة', got, [('د', 1), ('هـ', 1), ('ج', 3), ('ب', 4), ('أ', 5)])
check('اللي بدون اسم/بدون نقاط/بدون نادي/مخفي ما يطلعون', len(st), 5)
st, more = F.rank_fans({f'u{i}': M(f'م{i:02d}', 12, 6, 2, 1) for i in range(13)}, top=10)
check('13 متعادلين بالكامل: 10 يطلعون والباقي في more', (len(st), more, {x[3] for x in st}), (10, 3, {1}))

print(f'\nالنتيجة: {ok} نجح · {fail} فشل')
sys.exit(1 if fail else 0)
