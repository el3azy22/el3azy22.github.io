"""اختبارات الحسابات (بدون إنترنت): «دوري التوقعات» و«دوري الجماهير».
كل حالة: المدخلات ← القاعدة ← المتوقع (محسوب باليد) ← الفعلي.   python3 _tools/tests/test_scoring.py"""
import importlib.util, os, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
def load(name, path):
    sp = importlib.util.spec_from_file_location(name, os.path.join(ROOT, path)); m = importlib.util.module_from_spec(sp); sp.loader.exec_module(m); return m
P = load('pred', '_tools/predict/build.py')
F = load('fans', '_tools/fans/build.py')
ok = fail = 0
def check(name, got, want):
    global ok, fail
    good = got == want; ok += good; fail += not good
    print(('✅' if good else '❌'), name, '→', got, '' if good else f'(المتوقع {want})')

print('— نقاط مباراة التوقعات —')
for (ph, pa, sh, sa), want, why in [
    ((2, 1, 2, 1), 10, 'النتيجة بالضبط'), ((2, 1, 3, 2), 6, 'الفائز والفارق'), ((1, 1, 0, 0), 6, 'تعادل بنتيجة ثانية'),
    ((2, 1, 3, 0), 4, 'الفائز بس'), ((2, 1, 1, 1), 0, 'توقع فوز وصار تعادل'), ((0, 0, 0, 1), 0, 'توقع تعادل وفاز الضيف'),
    ((0, 0, 0, 0), 10, 'صفر-صفر بالضبط'), ((20, 0, 1, 0), 4, 'الفائز بس بفارق مختلف (حد أعلى 20)'), ((1, 2, 0, 1), 6, 'فوز الضيف بنفس الفارق')]:
    check(f'{why}: توقع {ph}-{pa} والنتيجة {sh}-{sa}', P.points(ph, pa, sh, sa), want)

print('\n— جولة توقعات كاملة —')
T0 = 1_800_000_000_000
ms = [{'id': 'A', 'wk': 5, 't': T0, 'h': 'ain', 'a': 'wahda', 'st': 6, 'sh': 2, 'sa': 1},
      {'id': 'B', 'wk': 5, 't': T0 + 3600e3, 'h': 'wasl', 'a': 'nasr', 'st': 6, 'sh': 0, 'sa': 0},
      {'id': 'C', 'wk': 5, 't': T0 + 7200e3, 'h': 'jazira', 'a': 'kalba', 'st': 4},          # تأجلت/ما خلصت
      {'id': 'D', 'wk': 6, 't': T0 + 7 * 86400e3, 'h': 'ajman', 'a': 'hatta', 'st': 6, 'sh': 1, 'sa': 3}]
pk = lambda h, a, w, x=False, c='ain', n='': {'h': h, 'a': a, 'w': w, 'c': c, 'n': n, **({'x': True} if x else {})}
picks = {'A': {'u1': pk(2, 1, T0 - 5, x=True), 'u2': pk(1, 0, T0 - 9), 'u3': pk(2, 1, T0)},          # u3 كتب مع الصافرة = مرفوض
         'B': {'u1': pk(1, 1, T0 - 5, x=True), 'u2': pk(0, 0, T0 - 9, x=True), 'u3': pk(0, 0, T0 - 1)},
         'C': {'u1': pk(1, 0, T0 - 5)},
         'D': {'u1': pk(0, 2, T0 - 5)}}
cr, tb = P.compute(ms, picks, T0 + 9 * 86400e3)
r5 = {row[0]: row for row in tb['rounds']['5']}
# u1: A بالضبط 10 ×2 (أول مضاعفة بالموعد) = 20 · B تعادل بنتيجة ثانية 6 (المضاعفة الثانية ما تنحسب) · C ما خلصت = 0 ⇒ 26، بالضبط 1، مباريات محسوبة 2
check('u1: 26 نقطة، 1 بالضبط، 2 مباريات', r5['u1'][3:6], [26, 1, 2])
# u2: A الفائز والفارق 6 · B بالضبط 10 ×2 = 20 ⇒ 26، بالضبط 1
check('u2: 26 نقطة، 1 بالضبط', r5['u2'][3:6], [26, 1, 2])
# u3: A مرفوض (مع الصافرة) · B بالضبط 10 ⇒ 10
check('u3: توقع مع الصافرة ما ينحسب ⇒ 10', r5['u3'][3:6], [10, 1, 1])
# تعادل u1 و u2 (26، 1 بالضبط): الأقدم في آخر توقع يتقدم. آخر كتابة u1 = T0-5 (C)، u2 = T0-9 ⇒ u2 أول
check('كسر التعادل: الأقدم في التوقع أول', [row[0] for row in tb['rounds']['5']][:2], ['u2', 'u1'])
check('آخر مباراة جابت نقاط لـu1 = B (C ما خلصت)', r5['u1'][6], T0 + 3600e3)
check('الموسم v2: مجموع الجولات بدون حد أدنى', sorted((x[0], x[3]) for x in tb['season']), [('u1', 32), ('u2', 26), ('u3', 10)])   # u1: + D في الجولة 6 (0-2 والنتيجة 1-3 = الفائز والفارق 6)
check('رأي الجماهير في A يحسب التوقعات المقبولة بس (2)', cr['A']['n'], 2)

# نادي كل توقع = نادي المشجع وقت ما كتبه: مشجع غيّر ناديه بين المباراتين
ms2 = [{'id': 'X', 'wk': 9, 't': T0, 'h': 'ain', 'a': 'wahda', 'st': 6, 'sh': 1, 'sa': 0},
       {'id': 'Y', 'wk': 9, 't': T0 + 3600e3, 'h': 'wasl', 'a': 'nasr', 'st': 6, 'sh': 2, 'sa': 2}]
_, tb2 = P.compute(ms2, {'X': {'k1': pk(1, 0, T0 - 9, c='ain')}, 'Y': {'k1': pk(0, 1, T0 - 5, c='wasl')}}, T0 + 86400e3)
check('نقاط X (10) للعين ونقاط Y (0) للوصل (التشكيلة: [نادي، 0، مشاركين، نقاط، أخطاء، عدد])', sorted(tuple(x) for x in tb2['clubs']['9']), [('ain', 0, 1, 10, 0, 1), ('wasl', 0, 1, 0, 1, 1)])
check('المعدل لخانتين بتقريب نص لفوق (33÷8 = 4.125 ⇒ 4.13)', (P.avg2(33, 8), F.avg2(33, 8), F.avg2(103, 25)), (4.13, 4.13, 4.12))

print('\n— آلية الترتيب الموحدة (المشجعين والأندية) —')
def st(pts, mis, plays, sec, c, nm='', ct=1):
    return dict(F.stat(), pts=pts, mis=mis, plays=plays, sec=sec, c=c, nm=nm, ct=ct)
mano = {'a': st(30, 4, 6, 900, 'ain', 'أأ'), 'b': st(30, 2, 6, 900, 'ain', 'بب'), 'c': st(30, 2, 7, 900, 'wasl', 'جج'),
        'd': st(30, 2, 7, 600, 'wasl', 'دد'), 'e': st(30, 2, 7, 600, 'nasr', 'هـ'), 'g': st(50, 0, 7, 100, 'ain', ''),
        'h': st(12, 3, 2, 50, 'hatta', 'حح'), 'i': st(10, 0, 2, 10, 'ain', 'طط')}
pred = {'h': st(20, 1, 3, 0, 'hatta', 'حح')}
bd, rk = F.boards({'mano': mano, 'pred': pred}, None, {'i'})
# كلهم 30 ما عدا ز (50 بدون اسم): أ أخطاء 4 (آخر) · ب أخطاء 2 لعب 6 · (ج، د، هـ) أخطاء 2 لعب 7: الأسرع د وهـ (600) قبل ج (900) · د وهـ متساوين ⇒ نفس المركز
# من 19 نوفمبر: أعلى المشجعين بالترتيب بدون فراغات، اللي بدون اسم (أو اسمه مخفي) يطلع '' = «مشجع»
check('المشجعين: النقاط ← الأقل أخطاء ← الأكثر لعب ← الأسرع، والتعادل الكامل نفس المركز',
      [(x[0], x[3]) for x in bd['mano']['fans']], [('', 1), ('دد', 2), ('هـ', 2), ('جج', 4), ('بب', 5), ('أأ', 6), ('حح', 7), ('', 8)])
check('اللي بدون اسم ياخذ مركزه وما يطلع اسمه · المخفي ما يطلع', (rk['g']['mano'][0], 'طط' in [x[0] for x in bd['mano']['fans']]), (1, False))
check('كل التحديات = منو اللاعب + التوقعات (ح: 12 + 20 = 32)', rk['h']['all'][1], 32)
check('لوحة التوقعات فيها اللي توقع بس', [x[0] for x in bd['pred']['fans']], ['حح'])
check('حرف واحد مب اسم: يطلع «مشجع» في أعلى المشجعين', [x[0] for x in F.boards({'mano': {'z': st(9, 0, 1, 5, 'ain', 'م')}}, None, set())[0]['mano']['fans']], [''])
# الأندية: التشكيلة = أفضل 11
many = {f'w{i:02d}': st(10 + i, 0, 7, 0, 'wahda') for i in range(15)}          # 15 مشجع: أفضل 11 = 14..24
few = {f'k{i}': st(30, 0, 7, 0, 'kalba') for i in range(4)}                    # 4 مشجعين قويين = 120
bd2, _ = F.boards({'mano': {**many, **few}}, None, set())
cl = {r[0]: r for r in bd2['mano']['clubs']}
check('الوحدة: 15 مشجع بس تنحسب أفضل 11 (14+…+24 = 209)', (cl['wahda'][2], cl['wahda'][3], cl['wahda'][4]), (209, 11, 15))
check('كلباء: 4 مشجعين يلعبون «ناقص» (120)', (cl['kalba'][2], cl['kalba'][3]), (120, 4))
check('العدد ما يفوز بروحه: الوحدة (209) قبل كلباء (120)', (cl['wahda'][1], cl['kalba'][1]), (1, 2))
two = {'x1': st(50, 3, 7, 100, 'ain'), 'y1': st(50, 1, 7, 900, 'wasl'), 'z1': st(50, 1, 7, 200, 'nasr')}
cl3 = {r[0]: r[1] for r in F.boards({'mano': two}, None, set())[0]['mano']['clubs']}
check('تعادل الأندية: الأقل أخطاء ثم الأسرع (النصر، الوصل، العين)', (cl3['nasr'], cl3['wasl'], cl3['ain']), (1, 2, 3))
ten = {f'u{i}': st(12, 0, 2, 5, 'ain', f'م{i:02d}') for i in range(13)}
b4 = F.boards({'mano': ten}, None, set())[0]['all']
check('13 متعادلين بالكامل: 10 يطلعون والباقي في more', (len(b4['fans']), b4['more'], {x[3] for x in b4['fans']}), (10, 3, {1}))
m1 = F.collect_mano({'3': {'easy': {'U1xxxxxxxxxxx': {'g': 2, 'c': 'ain', 't': 5, 'sec': 40}}, 'pro': {'U1xxxxxxxxxxx': {'g': 0, 'c': 'ain', 't': 6, 'sec': 5000}}}}, 1, 7)
check('منو اللاعب: نقاط 5، أخطاء 1+6، لعبتين، ثواني 40 + حد ساعة', [m1['U1xxxxxxxxxx'][k] for k in ('pts', 'mis', 'plays', 'sec')], [5, 7, 2, 3640])

print(f'\nالنتيجة: {ok} نجح · {fail} فشل')
sys.exit(1 if fail else 0)
